#!/usr/bin/env python3
"""Regenerates public/option-art-index.js from the files in public/library/options."""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent / 'public/library/options'
art = {}
for d in sorted(p for p in root.rglob('*') if p.is_dir()):
    files = {f.stem: f.suffix[1:] for f in sorted(d.iterdir()) if f.suffix in ('.webp', '.svg')}
    if files:
        art[d.relative_to(root).as_posix()] = files
# Makro kadrovi za čekanje rendera: <komad ili shared>/<kategorija>/<slug>.webp
details = {}
for f in sorted((root.parent / 'details').rglob('*.webp')):
    details.setdefault(f.parent.relative_to(root.parent / 'details').as_posix(), []).append(f.stem)
out = root.parent.parent / 'option-art-index.js'
out.write_text('// Generated by scripts/build_option_index.py, do not edit.\nexport const ART = ' + json.dumps(art, separators=(',', ':')) + ';\nexport const DETAILS = ' + json.dumps(details, separators=(',', ':')) + ';\n')
print(sum(len(v) for v in art.values()), sum(len(v) for v in details.values()))

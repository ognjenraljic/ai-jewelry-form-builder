import assert from 'node:assert/strict';
import { fromTemplate, DEFAULT_STYLES, publicForm, formFromOnboarding, styleOf, validateFormDef } from '../src/forms.js';
import { applyPresetTeeth, teethOptional } from '../public/grillz-selection.js';
import { fieldRequired, stepNeedsAnswer } from '../public/step-rules.js';
import { buildPrompt } from '../src/prompt.js';
let n = 0;
const check = (condition, message) => { assert.ok(condition, message); console.log(`OK ${++n} ${message}`); };
const form = fromTemplate('grillz', { id: 'qa-grillz', brand: 'QA' });
const marked = { type: 'grillz', style: 'top6' };
applyPresetTeeth(form, marked);
check(marked.teeth === 'T3,T4,T5,T6,T7,T8', 'a preset marks its teeth in the picker');
const answers = { type: 'grillz', style: 'top6', teeth: 'B5,B6' };
applyPresetTeeth(form, answers);
check(answers.teeth === 'B5,B6', 'teeth the customer changed after a preset stay exactly as chosen');
answers.style = 'other'; answers.teeth = 'T5,T6,B5,B6'; applyPresetTeeth(form, answers);
check(answers.teeth === 'T5,T6,B5,B6', 'custom two plus two remains exactly selected');
const onboarding = formFromOnboarding({ pieces: [{ value: 'grillz', label: 'Grillz', styles: [{ ...DEFAULT_STYLES.grillz[0], label: 'My classic grill' }] }] }, { id: 'qa-onboard', brand: 'QA' });
check(onboarding.styles.grillz[0].value === 'my-classic-grill' && onboarding.styles.grillz[0].teeth === DEFAULT_STYLES.grillz[0].teeth, 'renamed onboarding style retains its layout');
const legacy = structuredClone(onboarding); delete legacy.styles.grillz[0].teeth;
legacy.styles.grillz[0].image = '/media/forms/qa-onboard/style.webp';
check(publicForm(legacy).styles.grillz[0].teeth === DEFAULT_STYLES.grillz[0].teeth, 'existing renamed and copied library presets remain supported');
const photo = structuredClone(form);
photo.styles.grillz = [{ value: 'photo-style', label: 'My grill', image: '/library/grillz/set.webp', shape: 'a two-row design' }];
const p = buildPrompt(form, { ...answers, stones: 'lab', coverage: 'full' }, { refs: ['style'] });
check(p.includes('exactly 4 individual dental jewelry caps ONLY') && p.includes('Unselected positions must be empty background'), 'two plus two describes four physical objects, with no side filler');
check(p.includes('SURFACE DESIGN reference only') && !p.includes('Match its silhouette, proportions and number of elements closely'), 'a reference cannot override a custom tooth count');
const customStyle = { value: 'bespoke', label: 'Photo preset', image: '/media/forms/qa-grillz/style.webp', shape: 'two upper and two lower caps' };
photo.styles.grillz = [customStyle];
const photoAnswers = { type: 'grillz', style: 'bespoke', teeth: 'T3,T8' };
check(teethOptional(photo, { type: 'grillz', style: 'bespoke' }) && !teethOptional(form, { type: 'grillz', style: 'top6' }), 'teeth are optional only for a photo style with no known layout');
const teethStep = photo.steps.find((s) => s.id === 'teeth');
check(!fieldRequired(photo, teethStep, teethStep.fields[0], { type: 'grillz', style: 'bespoke' }) && fieldRequired(form, teethStep, teethStep.fields[0], { type: 'grillz', style: 'other' }), 'Something else must pick teeth, a photo style need not');
delete photoAnswers.teeth;
const photoPrompt = buildPrompt(photo, photoAnswers, { refs: ['style'], style: customStyle });
check(photoPrompt.includes('two upper and two lower caps') && !photoPrompt.includes('ONE row'), 'photo presets define their own coverage without an invented upper-only row');
const fangs = { type: 'grillz', style: 'fangs' }; applyPresetTeeth(form, fangs);
check(buildPrompt(form, fangs, { style: styleOf(form, fangs) }).includes('pointed and elongated'), 'fang presets retain the actual fang shape');
const design = form.steps.find((s) => s.id === 'design');
check(fieldRequired(form, design, design.fields[0], { type: 'grillz' }) && !fieldRequired(form, { ...design, optionalFor: ['grillz'] }, design.fields[0], { type: 'grillz' }), 'a step can be optional for one piece');
check(stepNeedsAnswer({ required: true }, { type: 'ring' }) && !stepNeedsAnswer({ required: true, optionalFor: ['ring'] }, { type: 'ring' }), 'a required step asks for an answer unless that piece skips it');
const invalid = structuredClone(form); invalid.styles.grillz[0].teeth = 'T11';
assert.throws(() => validateFormDef(invalid, invalid.id));
console.log(`Passed ${n + 1} style-flow checks.`);
